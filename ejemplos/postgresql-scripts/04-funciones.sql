-- Función, vista y trigger. Se puede ejecutar más de una vez.

CREATE OR REPLACE FUNCTION count_open_tasks()
RETURNS bigint
LANGUAGE sql
STABLE
AS $$
    SELECT COUNT(*) FROM tasks WHERE status <> 'done';
$$;

CREATE OR REPLACE FUNCTION tasks_by_status(p_status text)
RETURNS SETOF tasks
LANGUAGE sql
STABLE
AS $$
    SELECT *
    FROM tasks
    WHERE status = p_status
    ORDER BY created_at DESC;
$$;

CREATE OR REPLACE VIEW open_tasks AS
SELECT id, title, status, created_at, owner_id
FROM tasks
WHERE status <> 'done';

CREATE TABLE IF NOT EXISTS task_status_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL,
    old_status varchar(20),
    new_status varchar(20) NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION log_task_status()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO task_status_log (task_id, old_status, new_status)
        VALUES (NEW.id, OLD.status, NEW.status);
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_log_task_status ON tasks;

CREATE TRIGGER trg_log_task_status
AFTER UPDATE OF status ON tasks
FOR EACH ROW
EXECUTE FUNCTION log_task_status();

