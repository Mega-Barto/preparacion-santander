-- Esquema de referencia: usuarios, tareas y etiquetas (many-to-many).
-- Pensado para PostgreSQL 14+.

DROP TABLE IF EXISTS task_status_log;
DROP TABLE IF EXISTS task_tags;
DROP TABLE IF EXISTS tasks;
DROP TABLE IF EXISTS tags;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(180) NOT NULL UNIQUE,
    name varchar(120) NOT NULL
);

CREATE TABLE tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(180) NOT NULL,
    description text,
    status varchar(20) NOT NULL DEFAULT 'pending',
    created_at timestamptz NOT NULL DEFAULT now(),
    owner_id bigint REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT tasks_status_chk CHECK (status IN ('pending', 'in_progress', 'done'))
);

CREATE TABLE tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(40) NOT NULL UNIQUE
);

CREATE TABLE task_tags (
    task_id bigint NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    tag_id bigint NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (task_id, tag_id)
);

CREATE INDEX idx_tasks_status ON tasks (status);
CREATE INDEX idx_tasks_owner ON tasks (owner_id);

COMMENT ON COLUMN tasks.status IS 'pending | in_progress | done';
